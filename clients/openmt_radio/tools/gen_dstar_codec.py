#!/usr/bin/env python3
"""Extracts the D-STAR header coding (convolutional code, interleave, scrambling, CRC, Viterbi decoder) from
protocols/DSTAR/dstar_host.c into core/dstar_codec.c, so that the radio uses the host's own tables and code and not a copy
typed in by hand.  Run from clients/openmt_radio:  python3 tools/gen_dstar_codec.py"""
import re, sys

src = open('../../protocols/DSTAR/dstar_host.c').read().split('\n')

def find(pattern, start=0):
    for i in range(start, len(src)):
        if re.match(pattern, src[i]):
            return i
    raise SystemExit('not found: ' + pattern)

def block_end(i):
    """index of the line that ends the statement or function starting at i"""
    depth = 0
    started = False
    for j in range(i, len(src)):
        line = src[j]
        depth += line.count('{') - line.count('}')
        if '{' in line:
            started = True
        if started and depth == 0 and (line.strip().endswith('};') or line.strip() == '}'):
            return j
    raise SystemExit('no end')

def with_comment(i):
    """moves i back over the comment block above a function"""
    j = i - 1
    if src[j].strip() == '*/':
        while not src[j].strip().startswith('/*'):
            j -= 1
        return j
    return i

out = []
out.append('''/* D-STAR header coding for OpenMT Radio.
 *
 * GENERATED by tools/gen_dstar_codec.py from protocols/DSTAR/dstar_host.c: the tables, txHeader(), rxHeader() and the
 * Viterbi decoder are the host's own, so what the radio sends is what dstar_host decodes and the other way round.
 * Do not edit by hand; change dstar_host.c and run the script again. */

#include <stdbool.h>
#include <stdint.h>
#include <string.h>

#include "dstar_codec.h"

#define txHeader dstarTxHeader
#define rxHeader dstarRxHeader
#define checksum dstarChecksum
#define acs dstarAcs
#define viterbiDecode dstarViterbiDecode
#define traceBack dstarTraceBack

''')
# bit masks and macros
a = find(r'const uint8_t BIT_MASK_TABLE0')
b = find(r'#define READ_BIT1')
out += src[a:b + 1]
out.append('')
for name, pat in (('rx', r'const uint8_t INTERLEAVE_TABLE_RX'), ('srx', r'const uint8_t SCRAMBLE_TABLE_RX'),
                  ('crc', r'const uint16_t CCITT16_TABLE')):
    i = find(pat)
    out += src[i:block_end(i) + 1]
    out.append('')
i = find(r'static const uint8_t BIT_MASK_TABLE\[\]')
out += src[i:block_end(i) + 1]
out.append('')
for pat in (r'const uint8_t INTERLEAVE_TABLE_TX', r'const uint8_t SCRAMBLE_TABLE_TX'):
    i = find(pat)
    out += src[i:block_end(i) + 1]
    out.append('')
out += ['unsigned int mar;', 'int pathMetric[4U];', 'unsigned int pathMemory0[42U];', 'unsigned int pathMemory1[42U];',
        'unsigned int pathMemory2[42U];', 'unsigned int pathMemory3[42U];', 'uint8_t fecOutput[42U];', '']
out.append('#define DSTAR_HEADER_LENGTH_BYTES 41U')
out.append('#define DSTAR_FEC_SECTION_LENGTH_BYTES 83U')
out.append('')
for pat in (r'void txHeader\(const', r'void acs\(int', r'void viterbiDecode\(int', r'void traceBack\(\)', r'bool checksum\(const',
            r'bool rxHeader\(uint8_t'):
    i = find(pat + r'.*$', 700)
    # the definitions are after the forward declarations (line < 720)
    while ';' in src[i]:
        i = find(pat + r'.*$', i + 1)
    s = with_comment(i)
    out += src[s:block_end(i) + 1]
    out.append('')

out.append('''/* The CRC of a header, the one checksum() checks (CCITT-16, bytes 39 and 40) */
void dstarHeaderCrc(uint8_t* header)
{
    uint16_t crc = 0xFFFFU;

    for (unsigned int i = 0U; i < DSTAR_HEADER_LENGTH_BYTES - 2U; i++)
        crc = (uint16_t)((crc >> 8) ^ CCITT16_TABLE[(crc & 0xFFU) ^ header[i]]);

    crc = (uint16_t)~crc;
    header[DSTAR_HEADER_LENGTH_BYTES - 2U] = (uint8_t)(crc & 0xFFU);
    header[DSTAR_HEADER_LENGTH_BYTES - 1U] = (uint8_t)(crc >> 8);
}''')
text = '\n'.join(out) + '\n'
text = re.sub(r'(?m)^(const uint8_t|const uint16_t|unsigned int mar|int pathMetric|unsigned int pathMemory|uint8_t fecOutput)', r'static \1', text)
text = re.sub(r'(?m)^(void acs|void viterbiDecode|void traceBack|bool checksum)', r'static \1', text)
open('core/dstar_codec.c', 'w').write(text)
print('wrote core/dstar_codec.c')
